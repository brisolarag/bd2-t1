-- a:
-- UTILIZA FUNCAO SOMA PARA CALCULAR A SOMA DA QUANTIDADE E VALOR UNITARIO DE TODOS PEDIDOS RELIZADOS NA TABELA ASSOCIATIVA
-- JOIN NA TABELA PEDIDO PARA PEGAR OS PEDIDOS DO CLIENTE
-- JOIN NA TABELA PRODUTO PARA PEGAR O NOME DO PRODUTO
-- SOMA TODAS QUANTIDADES X VALOR UNITARIO COMO TOTAL
-- CONDICAO FINAL ONDE O TOTAL DEVE SER 1000
SELECT 
    ip.NUM_PEDIDO, 
    prod.COD_PRODUTO, 
    prod.NOME AS NOME_PRODUTO, 
    c.NOME AS NOME_CLIENTE,
    SUM(ip.QUANTIDADE * ip.VALOR_UNITARIO) AS TOTAL
FROM 
    ITEM_PEDIDO ip
JOIN 
    PEDIDO ped ON ped.NUM_PEDIDO = ip.NUM_PEDIDO
JOIN 
    CLIENTE c ON c.COD_CLIENTE = ped.COD_CLIENTE
JOIN 
    PRODUTO prod ON prod.COD_PRODUTO = ip.COD_PRODUTO
GROUP BY 
    ip.NUM_PEDIDO, 
    prod.COD_PRODUTO, 
    prod.NOME, 
    c.NOME
HAVING 
    SUM(ip.QUANTIDADE * ip.VALOR_UNITARIO) > 1000;

    
