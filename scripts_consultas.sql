FROM PESSOA_FISICA pf
JOIN 
    CLIENTE c ON c.COD_CLIENTE = pf.COD_CLIENTE
JOIN 
    PESSOA_JURIDICA pj ON pf.COD_EMPRESA = pj.COD_CLIENTE

--c:
-- APENAS CATEGORIAS COM COD_CATEGORIA_PAI SENDO NULOS
-- JOIN NA TABELA DE PRODUTO PARA AGRUPAR OS PRODUTOS POR CATEGORIA E CODIGO
-- UTILIZA FUNCAO COUNT
SELECT 
cat.COD_CATEGORIA, 
cat.NOME, 
COUNT(p.COD_PRODUTO) AS QUANTIDADE_PRODUTOS
FROM 
    CATEGORIA cat
JOIN 
    PRODUTO p ON p.COD_CATEGORIA = cat.COD_CATEGORIA
WHERE 
    cat.COD_CATEGORIA_PAI IS NULL
GROUP BY 
    cat.COD_CATEGORIA, 
    cat.NOME;

-- d:
-- AGRUPA AS CATEGORIAS PELO CODIGO E NOME
-- JOIN NA TABELA DE CATEGORIA PARA MOSTRAR O NOME
-- UTILIZA FUNCAO AVG E COUNT PARA MEDIA E TOTAL
SELECT 
c.COD_CATEGORIA, 
c.NOME AS NOME_CATEGORIA, 
COUNT(p.COD_PRODUTO) AS TOTAL_PRODUTOS, 
AVG(p.PRECO) AS MEDIA_PRECO
FROM 
    PRODUTO p
JOIN 
    CATEGORIA c ON c.COD_CATEGORIA = p.COD_CATEGORIA
WHERE
    p.IMPORTADO = 'S'
GROUP BY 
    c.COD_CATEGORIA, 
    c.NOME
ORDER BY 
    MEDIA_PRECO DESC;


