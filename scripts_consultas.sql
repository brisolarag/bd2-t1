-- UTILIZA LISTAGG PARA SEPARAR O NOME DOS FORNECEDORES POR , PARA EXIBIT O NOME DOS FORNECEDORES DO PRODUTO
-- SUM PARA CALCULAR AS QUANTIDADES
-- JOIN NA TABELA PRODUTO PARA EXIBIR AS INFORMACOES DO P E AGRUPAMENTO
-- JOIN NA TABALEA DE FORNECEDORES PARA EXIBIR O NOME DOS FORNECEDORES
SELECT 
    p.cod_produto,
    p.nome AS nome_produto,
    p.preco,
    LISTAGG(f.nome, ', ') WITHIN GROUP (ORDER BY f.nome) AS nome_fornecedor,
    SUM(pf.quantidade) AS quantidade_total
FROM 
    PRODUTO_FORNECEDOR pf
JOIN 
    PRODUTO p ON pf.cod_produto = p.cod_produto
JOIN 
    FORNECEDOR f ON pf.cod_fornecedor = f.cod_fornecedor
GROUP BY 
    p.cod_produto, p.nome, p.preco
ORDER BY 
    p.cod_produto;

